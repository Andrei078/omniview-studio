// Generates sw.js with the precache list and a content hash as the cache version:  node scripts/build-sw.mjs
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join } from "node:path";

export function buildSW(root = ".") {
const ROOT = ["index.html", "manifest.webmanifest"], DIRS = ["css", "js", "vendor", "fonts", "icons"];
const files = [...ROOT];
const walk = (d) => { for (const n of readdirSync(join(root, d))) { const p = join(d, n); statSync(join(root, p)).isDirectory() ? walk(p) : files.push(p.split("\\").join("/")); } };
DIRS.forEach(walk);
const hash = createHash("sha256");
for (const f of files.sort()) hash.update(f).update(readFileSync(join(root, f)));
const version = hash.digest("hex").slice(0, 10);
const sw = `// Generated by scripts/build-sw.mjs. Do not edit.
const CACHE = "omniview-${version}";
const FILES = ${JSON.stringify(["./", ...files], null, 1)};
self.addEventListener("install", (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES))); });
self.addEventListener("activate", (e) => { e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith("omniview-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("message", (e) => { if (e.data === "skip") self.skipWaiting(); });
self.addEventListener("fetch", (e) => {
  const r = e.request, u = new URL(r.url);
  if (r.method !== "GET" || u.origin !== location.origin) return;
  e.respondWith(caches.match(r, { ignoreSearch: true }).then((hit) => hit || fetch(r).catch(() => (r.mode === "navigate" ? caches.match("./index.html") : Response.error()))));
});
`;
return { sw, files, version };
}
if (process.argv[1]?.endsWith("build-sw.mjs")) { const r = buildSW("."); writeFileSync("sw.js", r.sw); console.log("sw.js written: " + r.files.length + " files, version " + r.version); }
